#!/usr/bin/env bash
# Low-latency tuning for the benchmark machine (Ubuntu Server 24.04, i5-10300H, 4 cores).
#
# Usage:
#   sudo ./setup-tuning.sh apply    # install boot params + runtime tuning service, then reboot
#   sudo ./setup-tuning.sh status   # show what is currently in effect
#   sudo ./setup-tuning.sh revert   # remove everything this script installed, then reboot
#
# Environment overrides:
#   ISOLATED=1-3          CPUs to isolate (CPU 0 stays housekeeping)
#   BASE_FREQ=2500MHz     frequency to lock (i5-10300H base clock)
#   BLOCK_WIRELESS=0      set to 1 to rfkill Wi-Fi/Bluetooth (only if you SSH over Ethernet!)
#
# Every change is in its own file so that revert is clean:
#   /etc/default/grub.d/99-low-latency.cfg
#   /usr/local/sbin/ll-runtime-tuning.sh
#   /etc/systemd/system/ll-runtime-tuning.service
set -euo pipefail

ISOLATED="${ISOLATED:-1-3}"
BASE_FREQ="${BASE_FREQ:-2500MHz}"
BLOCK_WIRELESS="${BLOCK_WIRELESS:-0}"

GRUB_CFG=/etc/default/grub.d/99-low-latency.cfg
RUNTIME_SCRIPT=/usr/local/sbin/ll-runtime-tuning.sh
UNIT=/etc/systemd/system/ll-runtime-tuning.service

# Services that wake up periodically or move work onto isolated cores.
NOISY_SERVICES=(irqbalance snapd snapd.socket unattended-upgrades ondemand ModemManager bluetooth
                apt-daily.timer apt-daily-upgrade.timer motd-news.timer fwupd-refresh.timer)

KERNEL_PARAMS=(
  "nosmt"                              # disable hyper-threading siblings
  "isolcpus=${ISOLATED}"               # scheduler keeps ordinary tasks off these CPUs
  "nohz_full=${ISOLATED}"              # stop the scheduler tick when one task runs
  "rcu_nocbs=${ISOLATED}"              # move RCU callbacks to housekeeping CPU
  "irqaffinity=0"                      # default IRQ affinity: CPU 0
  "intel_idle.max_cstate=0"            # disable intel_idle driver's deep C-states
  "processor.max_cstate=1"             # cap ACPI C-states at C1
  "transparent_hugepage=never"         # no khugepaged compaction jitter (explicit huge pages later)
  "nmi_watchdog=0"
  "nowatchdog"
  "skew_tick=1"                        # avoid all CPUs ticking at the same instant
)

need_root() { [[ $EUID -eq 0 ]] || { echo "Run with sudo." >&2; exit 1; }; }

write_runtime_script() {
  cat > "$RUNTIME_SCRIPT" <<EOF
#!/usr/bin/env bash
# Generated by setup-tuning.sh — runtime tuning applied at every boot.
set -u
# 1. Turbo off, frequency locked
echo 1 > /sys/devices/system/cpu/intel_pstate/no_turbo 2>/dev/null || echo "warn: cannot disable turbo"
cpupower frequency-set -g performance >/dev/null 2>&1 || echo "warn: cannot set governor"
cpupower frequency-set -d ${BASE_FREQ} -u ${BASE_FREQ} >/dev/null 2>&1 || echo "warn: cannot lock frequency"

# 2. Push every movable IRQ to CPU 0
for irq in /proc/irq/*/smp_affinity_list; do
  echo 0 > "\$irq" 2>/dev/null || true
done

# 3. Kernel workqueues on CPU 0 only (bitmask 0x1)
echo 1 > /sys/devices/virtual/workqueue/cpumask 2>/dev/null || true

# 4. Fewer periodic kernel wake-ups
sysctl -q -w vm.stat_interval=120 || true
sysctl -q -w kernel.watchdog=0 || true
sysctl -q -w kernel.numa_balancing=0 2>/dev/null || true

# 5. Optional: radio off (only when connected via Ethernet)
if [[ "${BLOCK_WIRELESS}" == "1" ]]; then
  rfkill block wifi bluetooth || true
fi
EOF
  chmod 0755 "$RUNTIME_SCRIPT"
}

write_unit() {
  cat > "$UNIT" <<EOF
[Unit]
Description=Low-latency runtime tuning (benchmark machine)
After=multi-user.target

[Service]
Type=oneshot
ExecStart=${RUNTIME_SCRIPT}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
}

apply() {
  need_root
  command -v cpupower >/dev/null || { echo "Install linux-tools first: apt install linux-tools-common linux-tools-\$(uname -r)" >&2; exit 1; }

  mkdir -p /etc/default/grub.d
  {
    echo "# Generated by setup-tuning.sh on $(date -Iseconds)"
    echo "GRUB_CMDLINE_LINUX_DEFAULT=\"\$GRUB_CMDLINE_LINUX_DEFAULT ${KERNEL_PARAMS[*]}\""
  } > "$GRUB_CFG"
  update-grub

  write_runtime_script
  write_unit
  systemctl daemon-reload
  systemctl enable ll-runtime-tuning.service

  for s in "${NOISY_SERVICES[@]}"; do
    if systemctl cat "$s" >/dev/null 2>&1; then
      systemctl disable --now "$s" >/dev/null 2>&1 && echo "disabled $s" || true
    fi
  done

  echo
  echo "Kernel parameters written to $GRUB_CFG:"
  cat "$GRUB_CFG"
  echo
  echo "Reboot now, then run: sudo $0 status"
}

status() {
  echo "== /proc/cmdline";               cat /proc/cmdline
  echo "== online CPUs";                 cat /sys/devices/system/cpu/online
  echo "== isolated CPUs";               cat /sys/devices/system/cpu/isolated
  echo "== nohz_full";                   cat /sys/devices/system/cpu/nohz_full 2>/dev/null || echo "(n/a)"
  echo "== SMT active";                  cat /sys/devices/system/cpu/smt/active 2>/dev/null || echo "(n/a)"
  echo "== turbo disabled (1 = yes)";    cat /sys/devices/system/cpu/intel_pstate/no_turbo 2>/dev/null || echo "(n/a)"
  echo "== frequency";                   cpupower frequency-info -p 2>/dev/null; grep MHz /proc/cpuinfo
  echo "== THP";                         cat /sys/kernel/mm/transparent_hugepage/enabled
  echo "== runtime service";             systemctl is-active ll-runtime-tuning.service || true
  echo "== noisy services";
  for s in "${NOISY_SERVICES[@]}"; do printf "  %-28s %s\n" "$s" "$(systemctl is-active "$s" 2>/dev/null || true)"; done
  echo "== IRQs not on CPU 0";
  for irq in /proc/irq/[0-9]*; do
    aff=$(cat "$irq/smp_affinity_list" 2>/dev/null || echo "?")
    [[ "$aff" != "0" ]] && echo "  irq $(basename "$irq"): $aff"
  done
  true
}

revert() {
  need_root
  rm -f "$GRUB_CFG"
  update-grub
  systemctl disable ll-runtime-tuning.service >/dev/null 2>&1 || true
  rm -f "$UNIT" "$RUNTIME_SCRIPT"
  systemctl daemon-reload
  for s in "${NOISY_SERVICES[@]}"; do
    systemctl enable "$s" >/dev/null 2>&1 || true
  done
  echo "Reverted. Reboot to return to the default kernel command line."
}

case "${1:-}" in
  apply)  apply ;;
  status) status ;;
  revert) revert ;;
  *) echo "usage: sudo $0 {apply|status|revert}" >&2; exit 2 ;;
esac
